#!/usr/bin/env python3
"""Generate annotator/config.js from .env so the Supabase auth gate can run.

The annotator is a plain HTML page (it also runs from file://), so the browser
cannot read .env itself. This script turns .env into a tiny script file that
sets window.SUPABASE_CONFIG; annotator.html loads it before auth.js.

    cp .env.example .env      # then paste your project URL + anon key
    python3 gen_config.py

Placeholder values produce window.SUPABASE_CONFIG = null, which keeps the
annotator in local-only mode (no login gate, no network calls).
"""

from __future__ import annotations

import json
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
ENV_PATH = ROOT / ".env"
OUT_PATH = ROOT / "annotator" / "config.js"
CDN = "https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2/dist/umd/supabase.js"

PLACEHOLDER = re.compile(r"^(?:<.*>|your[-_].*|replace.?me|x{3,}|example.*)$", re.IGNORECASE)
LINE = re.compile(r"^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$")


def parse_env(path: pathlib.Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = LINE.match(line)
        if not match:
            continue
        value = match.group(2).strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[match.group(1)] = value.strip()
    return values


def main() -> int:
    env = parse_env(ENV_PATH)
    # Real environment variables win over .env, so CI (Vercel, GitHub Actions)
    # can inject the same names without writing a file.
    for name in ("SUPABASE_URL", "SUPABASE_ANON_KEY", "SUPABASE_ANON_PUBLIC_KEY", "SUPABASE_ALLOW_SIGNUP"):
        if os.environ.get(name, "").strip():
            env[name] = os.environ[name].strip()
    url = env.get("SUPABASE_URL", "").strip().rstrip("/")
    key = (env.get("SUPABASE_ANON_KEY") or env.get("SUPABASE_ANON_PUBLIC_KEY") or "").strip()
    allow_signup = env.get("SUPABASE_ALLOW_SIGNUP", "true").strip().lower() not in {"0", "false", "no", "off"}

    configured = bool(url) and bool(key) and not PLACEHOLDER.match(url) and not PLACEHOLDER.match(key)
    if configured and not url.startswith(("http://", "https://")):
        url = "https://" + url

    config = {"url": url, "anonKey": key, "allowSignup": allow_signup, "cdn": CDN} if configured else None
    payload = json.dumps(config, indent=2) if config else "null"
    OUT_PATH.write_text(
        "// Generated by gen_config.py from .env — do not edit by hand; rerun the script instead.\n"
        f"window.SUPABASE_CONFIG = {payload};\n",
        encoding="utf-8",
    )
    state = "configured" if config else "not configured (local-only mode)"
    print(f"wrote {OUT_PATH.relative_to(ROOT)} — Supabase {state}")
    if not ENV_PATH.exists() and not any(env.values()):
        print("note: no .env found — copy .env.example to .env, or set SUPABASE_URL / SUPABASE_ANON_KEY as environment variables", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
